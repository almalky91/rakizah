/**
 * Generates a unique message ID using timestamp and random string
 * This ensures each message in the conversation history has a unique identifier
 * 
 * @returns A unique string identifier for a message
 */
export const generateMessageId = (): string => {
  const timestamp = Date.now();
  const randomPart = Math.random().toString(36).substring(2, 9);
  return `msg-${timestamp}-${randomPart}`;
};
