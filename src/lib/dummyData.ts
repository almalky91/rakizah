/**
 * Helper function to get a conversation by skill ID
 * Returns fallback conversation if skill not found
 */
export const getConversation = (skillId: string): SkillConversation => {
  const conversation = dummyData.conversations[skillId];
  
  if (!conversation) {
    console.warn(`No conversation data found for skill: ${skillId}`);
    return createFallbackConversation(skillId);
  }
  
  return conversation;
};

/**
 * Helper function to get a specific node from a conversation
 * Returns null if node not found
 */
export const getNode = (
  conversation: SkillConversation,
  nodeId: string
): ConversationNode | null => {
  return conversation.nodes[nodeId] || null;
};

